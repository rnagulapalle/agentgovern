import { createRequire } from 'node:module';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const require = createRequire(import.meta.url);
const tsxRequire = createRequire(require.resolve('tsx'));
const { build } = tsxRequire('esbuild');
const { bundleWorkflowCode } = await import('@temporalio/worker');
const profile=process.argv[2]??'ack';if(!['ack','quote'].includes(profile))throw Error('Explicit supported worker profile required');
const prefix=profile==='quote'?'quote-temporal':'temporal';
await mkdir('.worker', { recursive: true });
const bundle = await bundleWorkflowCode({ workflowsPath: new URL(profile==='quote'?'../runtime/temporal/pinned-quote-workflow.ts':'../runtime/temporal/pinned-workflow.ts', import.meta.url).pathname });
await writeFile(`.worker/${prefix}-workflow.cjs`, bundle.code);
await build({ entryPoints: ['scripts/temporal-service.ts'], bundle: true, platform: 'node', format: 'cjs', outfile: `.worker/${prefix}-service.cjs`, external: ['pg-native', '@temporalio/worker', '@temporalio/client'] });
const artifactHash = createHash('sha256').update(await readFile(`.worker/${prefix}-service.cjs`)).update(bundle.code).update(await readFile('pnpm-lock.yaml')).digest('hex');
await writeFile(`.worker/${prefix}-manifest.json`, JSON.stringify({ version:1, artifactHash, buildId:`${profile}-${artifactHash}` })+'\n');
console.log('Temporal service and deterministic workflow bundles built with content-bound deployment version.');
