export async function validateConnectorProofSources(root=process.cwd(),sources:readonly string[]=connectorProofSources){
 const base=resolve(root),result:Record<string,string>={};
 if(!sources.length||new Set(sources).size!==sources.length)throw Error('Closed proof source inventory required');
 for(const file of sources){
  if(typeof file!=='string'||!/^[-a-zA-Z0-9_./]+$/.test(file)||file.split('/').some(p=>p==='..'||p==='.'||!p))throw Error('Proof source path refused');
  const path=resolve(base,file);if(!path.startsWith(base+sep))throw Error('Proof source path refused');
  const before=await lstat(path);if(!before.isFile()||before.size>2097152)throw Error('Proof source unavailable');
  const bytes=await readFile(path),after=await lstat(path);
  if(bytes.length!==before.size||before.dev!==after.dev||before.ino!==after.ino||before.size!==after.size||before.mtimeMs!==after.mtimeMs)throw Error('Proof source changed');
  result[file]=createHash('sha256').update(bytes).digest('hex');
 }
 return Object.freeze(result);
}
